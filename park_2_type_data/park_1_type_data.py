# tipe data integer
a = 30
print("tipe data integer : {0}".format(a))
# float
b = 3.14
print("tipe data float : {0}". format (b))
# complex
c = 2 - 2j
print("tipe data complex : {0}". format (c))
# sequensial type
# list
d = [1, 2, 3, 4, 5]
print("tipe data list : {0}". format (d))
#  tuple
e = (1, 2, 3, 4, 5)
print ("tipe data tuple : {0}". format (e))
# range
f = range(6)
print ("tipe data range : {0}". format (f))

# mapping type
# dictionary
g = {"nama": "arinald", "umur": 20}
print ("tipe data dictionary : {0}". format (g["umur"]))
# set type
# set
h = {1,2,3,4,5}
print ("tipe data set : {0}". format (h))
# frozenset
i = frozenset(e)
print ("tipe data frozenset : {0}". format (i))

z = 3
print ("ini ada adalah tipe data integer : {0}". format (z))

# boolean type
# boolean nilai true (1) atau false (0)
j = True
print ("Tipe data boolean : {0}". format (j))

# char
huruf = 'c'
print ("Tipe data char : {0}". format (huruf))

# string
k = "ini adalah contoh data string"
print ("ini contoh tipe data string : {0}". format (k))

